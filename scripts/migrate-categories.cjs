function migrate(targetPath) {
  console.log('Migrating categories in:', targetPath);
  const db = new Database(targetPath);
  const insert = db.prepare('INSERT OR IGNORE INTO categories (id, name, catord, lvl) VALUES (?, ?, 0, 0)');
  const update = db.prepare("UPDATE categories SET name = ? WHERE id = ? AND name LIKE 'Kategori sumber %'");
  
  let added = 0;
  let updated = 0;

  const txn = db.transaction(() => {
    for (const [idStr, name] of Object.entries(KNOWN_SOURCE_CATEGORIES)) {
      const id = parseInt(idStr, 10);
      const res = insert.run(id, name);
      if (res.changes > 0) added++;
      else {
        const u = update.run(name, id);
        if (u.changes > 0) updated++;
      }
    }
  });

  txn();
  const total = db.prepare('SELECT count(*) as c FROM categories').get().c;
  console.log(`Done! Added: ${added}, Updated: ${updated}, Total categories now: ${total}`);
  db.close();
}

const target = process.argv[2] || 'D:/db/maktabah.db';
migrate(target);
