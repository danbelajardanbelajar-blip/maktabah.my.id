/**
 * Mengembalikan nama kategori resmi jika diketahui,
 * atau fallback ke 'Kategori sumber #ID' jika tidak terdaftar.
 */
export function resolveCategoryName(id) {
  if (id == null) return 'غير مصنف';
  const numId = Number(id);
  if (KNOWN_SOURCE_CATEGORIES[numId]) {
    return KNOWN_SOURCE_CATEGORIES[numId];
  }
  return `Kategori sumber #${numId}`;
}

/**
 * Menghasilkan ekspresi CASE SQL untuk resolusi nama kategori dari ID.
 * @param {string} columnRef Referensi kolom ID kategori (misal: 'b.cat')
 * @returns {string} Ekspresi SQL CASE
 */
export function buildCategorySqlCase(columnRef = 'b.cat') {
  const whens = Object.entries(KNOWN_SOURCE_CATEGORIES)
    .map(([id, name]) => `WHEN ${id} THEN '${name.replace(/'/g, "''")}'`)
    .join(' ');
  return `CASE ${columnRef} ${whens} ELSE 'Kategori sumber #' || ${columnRef} END`;
}
